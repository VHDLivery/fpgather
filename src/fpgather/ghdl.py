"""Render analysis-only GHDL scripts without shell interpolation."""

import os
import shlex
from collections.abc import Sequence
from pathlib import Path

from .manifest import normalize_library_name
from .model import Source, SourcesError

STANDARDS = {
    "87": "87",
    "1987": "87",
    "93": "93",
    "1993": "93",
    "93c": "93c",
    "00": "00",
    "2000": "00",
    "02": "02",
    "2002": "02",
    "08": "08",
    "2008": "08",
    "19": "19",
    "2019": "19",
}

STANDARD_ORDER = ("87", "93", "93c", "00", "02", "08", "19")

# Exclude output paths, compiler forwarding and response files.
ANALYSIS_OPTIONS = frozenset(
    {
        "-frelaxed",
        "-frelaxed-rules",
        "-fexplicit",
        "-fsynopsys",
        "-fpsl",
        "-fcolor-diagnostics",
        "-fno-color-diagnostics",
        "-fdiagnostics-show-option",
        "-fno-diagnostics-show-option",
        "-fcaret-diagnostics",
        "-fno-caret-diagnostics",
    }
)


def _quote(value: str | Path) -> str:
    text = str(value)
    if "\0" in text:
        raise SourcesError("GHDL arguments cannot contain a NUL character")
    return shlex.quote(text)


def render_script(
    sources: list[Source],
    output: Path,
    *,
    build_dir: str | Path,
    ghdl: str | Path,
    analysis_options: Sequence[str],
    ghdl_standard: str | None = None,
) -> str:
    """Validate inputs and render Bash with fixed absolute paths."""
    if output.suffix.lower() != ".sh":
        raise SourcesError("GHDL script output must have the .sh suffix")
    if isinstance(analysis_options, (str, bytes)):
        raise SourcesError("GHDL analysis options must be a sequence of flags")
    options = list(analysis_options)
    for option in options:
        if not isinstance(option, str) or option not in ANALYSIS_OPTIONS:
            raise SourcesError(
                f"Unsupported GHDL analysis option: {option!r}; allowed: "
                + ", ".join(sorted(ANALYSIS_OPTIONS))
            )
    if (
        ghdl_standard not in (None, "highest")
        and ghdl_standard not in STANDARDS
    ):
        raise SourcesError(
            f"Unsupported GHDL standard override: {ghdl_standard!r}"
        )
    executable = os.fspath(ghdl)
    if not executable:
        raise SourcesError("GHDL executable must not be empty")
    if "/" in executable:
        executable = str(Path(executable).resolve())
    build = Path(build_dir).resolve()
    entries = []
    libraries = []
    for source in sources:
        path = Path(source.path).resolve()
        library = normalize_library_name(source.library)
        if library == "std":
            raise SourcesError("GHDL cannot analyze sources into library std")
        if path.suffix.lower() not in {".vhd", ".vhdl", ".hdl"}:
            raise SourcesError(f"Unsupported GHDL source suffix: {path}")
        standard = STANDARDS.get(source.language_version)
        if standard is None:
            raise SourcesError(
                f"Unsupported GHDL VHDL standard "
                f"{source.language_version!r}: {path}"
            )
        if not path.is_file():
            raise SourcesError(f"Source file not found: {path}")
        if path == output:
            raise SourcesError(f"GHDL output would overwrite a source: {path}")
        if library not in libraries:
            libraries.append(library)
        entries.append((path, library, standard))

    common_standard = None
    if ghdl_standard == "highest" and entries:
        common_standard = max(
            (entry[2] for entry in entries), key=STANDARD_ORDER.index
        )
    elif ghdl_standard not in (None, "highest"):
        common_standard = STANDARDS[ghdl_standard]

    lines = [
        "#!/usr/bin/env bash",
        "# Generated by fpgather. Analysis only; source files stay in place.",
        "set -euo pipefail",
        "",
        f"build_dir={_quote(build)}",
        f"ghdl=({_quote(executable)})",
        "# Resolve the executable before changing the working directory.",
        'executable=$(command -v -- "${ghdl[0]}")',
        'case "$executable" in',
        "  /*) ;;",
        '  *) executable="$PWD/$executable" ;;',
        "esac",
        'ghdl=("$executable")',
        "",
        "# Reject symlinks that could redirect compiler output.",
        'if [[ -L "$build_dir" ]]; then',
        '  echo "Build directory must not be a symlink" >&2',
        "  exit 2",
        "fi",
        'mkdir -p -- "$build_dir"',
        'if [[ -n "$(find "$build_dir" -type l -print -quit)" ]]; then',
        '  echo "Build directory must not contain symlinks" >&2',
        "  exit 2",
        "fi",
        'cd -- "$build_dir"',
        'mkdir -p -- "$build_dir/.tmp"',
        'export TMPDIR="$build_dir/.tmp"',
        'export TMP="$TMPDIR" TEMP="$TMPDIR"',
    ]
    for library in libraries:
        lines.append(f"mkdir -p -- {_quote(build / library)}")
    lines.append("search_paths=(")
    lines.extend(f"  {_quote('-P' + str(build / lib))}" for lib in libraries)
    lines.extend([")", ""])
    for path, library, standard in entries:
        # --std resets -frelaxed-rules, so emit the standard first.
        arguments = [
            "-a",
            f"--std={common_standard or standard}",
            *options,
            f"--work={library}",
            f"--workdir={build / library}",
        ]
        lines.append('command=( "${ghdl[@]}"')
        lines.extend(f"  {_quote(arg)}" for arg in arguments)
        lines.extend(
            [
                '  "${search_paths[@]}"',
                f"  {_quote(path)}",
                ")",
                '"${command[@]}"',
                "",
            ]
        )
    return "\n".join(lines) + "\n"
